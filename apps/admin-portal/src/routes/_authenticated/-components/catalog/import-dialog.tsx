// oxlint-disable react-perf/jsx-no-new-array-as-prop react-perf/jsx-no-new-function-as-prop
import { useEffect, useState } from "react";

import { Schema } from "effect";

import { standardSchemaResolver } from "@hookform/resolvers/standard-schema";
import type { ImportCatalogRequest, ImportCatalogResponse } from "@namera-ai/protocol/dto";
import { Button, Field, FieldLabel, FieldError, Input, Modal, toast } from "@namera-ai/ui";
import { Controller, useForm } from "react-hook-form";

import { useImportCatalog } from "@/hooks/catalog";
import { catalogErrorMessage } from "@/lib/catalog-feedback";

import { CatalogImportForm, readCatalogFile } from "./import-form";

export function ImportCatalogDialog({ onClose }: { onClose: () => void }) {
  const [payload, setPayload] = useState<ImportCatalogRequest | null>(null);
  const [preview, setPreview] = useState<typeof ImportCatalogResponse.Type | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [reading, setReading] = useState(false);
  const upload = useImportCatalog({
    onSuccess: (result) => {
      if (result.dryRun) setPreview(result);
      else {
        toast.success("Catalog imported", { description: "The address catalog is up to date." });
        onClose();
      }
    },
    onError: (failure) => setError(catalogErrorMessage(failure)),
  });
  const { reset } = upload;
  useEffect(() => () => reset(), [reset]);
  const form = useForm<typeof CatalogImportForm.Type>({
    resolver: standardSchemaResolver(Schema.toStandardSchemaV1(CatalogImportForm)),
  });
  const pending = reading || upload.isPending;

  async function previewFile({ file }: typeof CatalogImportForm.Type) {
    setReading(true);
    setError(null);
    setPreview(null);
    try {
      const parsed = await readCatalogFile(file);
      setPayload(parsed);
      upload.mutate({ payload: parsed, query: { dryRun: true } });
    } catch (failure) {
      setPayload(null);
      setError(
        failure instanceof Error
          ? failure.message
          : "Couldn’t read this file. Choose a valid catalog JSON file.",
      );
    } finally {
      setReading(false);
    }
  }

  return (
    <Modal
      isOpen
      onOpenChange={(open) => {
        if (!open && !pending) onClose();
      }}
    >
      <Modal.Backdrop isDismissable={!pending} isKeyboardDismissDisabled={pending}>
        <Modal.Container size="lg">
          <Modal.Dialog>
            <Modal.CloseTrigger isDisabled={pending} />
            <Modal.Header>
              <Modal.Heading>Upload catalog JSON</Modal.Heading>
            </Modal.Header>
            <Modal.Body className="grid gap-5">
              <p className="text-muted text-sm">
                Upload the JSON generated by your catalog builder. Review the changes before
                importing. Records missing from the file are left unchanged.
              </p>
              <form id="catalog-import-form" noValidate onSubmit={form.handleSubmit(previewFile)}>
                <Controller
                  control={form.control}
                  name="file"
                  render={({ field, fieldState }) => (
                    <Field data-invalid={fieldState.invalid}>
                      <FieldLabel htmlFor="catalog-file">Catalog file</FieldLabel>
                      <Input
                        id="catalog-file"
                        type="file"
                        accept=".json,application/json"
                        ref={field.ref}
                        name={field.name}
                        onBlur={field.onBlur}
                        disabled={pending}
                        fullWidth
                        variant="secondary"
                        aria-invalid={fieldState.invalid}
                        aria-describedby="catalog-file-help"
                        onChange={(event) => {
                          field.onChange(event.target.files?.[0]);
                          setPayload(null);
                          setPreview(null);
                          setError(null);
                        }}
                      />
                      <p id="catalog-file-help" className="text-muted text-xs">
                        JSON · Up to 2 MiB · Version 1
                      </p>
                      {fieldState.invalid ? <FieldError errors={[fieldState.error]} /> : null}
                    </Field>
                  )}
                />
              </form>
              {error ? (
                <p
                  role="alert"
                  className="text-danger max-h-40 overflow-auto whitespace-pre-wrap break-words text-sm"
                >
                  {error}
                </p>
              ) : null}
              {preview ? (
                <div className="grid gap-3" aria-live="polite">
                  <p className="text-sm font-medium">Ready to import</p>
                  <dl className="grid gap-2 text-sm">
                    {(["catalog", "entries", "interfaces"] as const).map((kind) => {
                      const counts = preview[kind];
                      return (
                        <div key={kind} className="flex justify-between gap-3">
                          <dt>
                            {kind === "catalog"
                              ? "Catalog records"
                              : kind === "entries"
                                ? "Deployments"
                                : "Interfaces"}
                          </dt>
                          <dd className="text-muted tabular-nums">
                            {counts.created} new ·{" "}
                            {"updated" in counts ? `${counts.updated} updated · ` : ""}
                            {counts.unchanged} unchanged
                          </dd>
                        </div>
                      );
                    })}
                  </dl>
                  <p className="text-muted text-xs">
                    Changes are applied together. The server rechecks the file when you import it.
                  </p>
                </div>
              ) : null}
            </Modal.Body>
            <Modal.Footer>
              {preview && payload ? (
                <Button
                  fullWidth
                  isDisabled={pending}
                  onPress={() => {
                    setError(null);
                    upload.mutate({ payload, query: { dryRun: false } });
                  }}
                >
                  {pending ? "Importing…" : "Import catalog"}
                </Button>
              ) : (
                <Button fullWidth form="catalog-import-form" type="submit" isDisabled={pending}>
                  {pending ? "Checking…" : "Review changes"}
                </Button>
              )}
            </Modal.Footer>
          </Modal.Dialog>
        </Modal.Container>
      </Modal.Backdrop>
    </Modal>
  );
}
