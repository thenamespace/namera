// Writes the ABIs of the deployed contracts from the Foundry build (contracts/out) to src/abis.
// Run `forge build` in contracts/ first.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const FOUNDRY_OUT = "../../contracts/out";
const OUT_DIR = "src/abis";

const CONTRACTS = [
  { artifact: "SmartSession.sol/SmartSession.json", name: "smartSession", file: "smart-session" },
  {
    artifact: "ECDSASessionValidator.sol/ECDSASessionValidator.json",
    name: "ecdsaSessionValidator",
    file: "ecdsa-session-validator",
  },
];

mkdirSync(OUT_DIR, { recursive: true });
for (const { artifact, name, file } of CONTRACTS) {
  const { abi } = JSON.parse(readFileSync(`${FOUNDRY_OUT}/${artifact}`, "utf8")) as {
    abi: unknown;
  };
  writeFileSync(
    `${OUT_DIR}/${file}.ts`,
    `// Generated by scripts/generate-abis.ts from ${artifact}. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(abi)} as const;\n`,
  );
}
writeFileSync(
  `${OUT_DIR}/index.ts`,
  CONTRACTS.map(({ name, file }) => `export { ${name}Abi } from "./${file}.ts";\n`).join(""),
);
